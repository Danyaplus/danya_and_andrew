export function translateGameRuntimeMessage(value, language, translate) {
  if (language === 'ru') return null;
  for (const [pattern, format] of patterns) {
    const match = value.match(pattern);
    if (match) return format(match, language, (part) => translate(part, language));
  }
  for (const [ru, uk, en] of fullSuffixes) {
    if (value.length > ru.length && value.endsWith(ru)) {
      return value.slice(0, -ru.length) + (language === 'uk' ? uk : en);
    }
  }
  // Player-action phrase with variable numbers or names; only a whole
  // standalone action is translated, never arbitrary parts of a username.
  for (const [pattern, uk, en] of playerActionPatterns) {
    const match = value.match(pattern);
    if (!match) continue;
    const quantity = quantities[match[3]]?.[language] || translate(match[3], language);
    return `${match[1]} ${language === 'uk' ? uk : en} ${match[2]} ${quantity}.`;
  }
  return null;
}
